// ═══════════════════════════════════════════════════════════════════════════
// SELF-HOST FONTS — download the Google-Fonts woff2 subsets actually used by
// the platform (Cairo 400/500/600/700 arabic+latin, Inter 400/500/600/700
// latin+latin-ext), store them in public/fonts/, and generate src/fonts.css
// with @font-face + unicode-range blocks (URLs rewritten to /fonts/…).
//
// WHY: the hosted fonts.googleapis.com CSS + font chain arrives after first
// paint (paint is JS-gated), so Cairo/Inter SWAPPED IN over the system
// fallback and re-flowed every Arabic text block — pushing the footer off the
// initial viewport: CLS 0.4 measured on the homepage. Self-hosted + preloaded
// fonts arrive before first paint → no swap → no reflow → CLS ≈ 0, plus one
// less third-party dependency (privacy + CSP + perf).
//
// Usage: node scripts/selfhost_fonts.mjs
// ═══════════════════════════════════════════════════════════════════════════
import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Cairo:wght@400;500;600;700&display=swap";
// Chrome UA → Google serves woff2 with per-subset unicode-range blocks
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";

const KEEP_SUBSETS = new Set(["arabic", "latin", "latin-ext"]);

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();

// Parse blocks: /* subset */ @font-face { ... }
const blocks = [];
const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g;
let m;
while ((m = re.exec(css)) !== null) {
  blocks.push({ subset: m[1], face: m[2] });
}

const kept = blocks.filter((b) => KEEP_SUBSETS.has(b.subset));
console.log(`fetched ${blocks.length} subsets, keeping ${kept.length} (arabic/latin/latin-ext)`);

await mkdir(path.resolve("public/fonts"), { recursive: true });

const out = [];
let i = 0;
for (const b of kept) {
  const urlMatch = b.face.match(/url\((https:[^)]+\.woff2)\)/);
  if (!urlMatch) continue;
  const famMatch = b.face.match(/font-family:\s*'([^']+)'/);
  const weightMatch = b.face.match(/font-weight:\s*(\d+)/);
  const fam = famMatch[1].toLowerCase();
  const weight = weightMatch[1];
  const fname = `${fam}-${weight}-${b.subset}.woff2`;
  const buf = Buffer.from(await (await fetch(urlMatch[1])).arrayBuffer());
  await writeFile(path.resolve("public/fonts", fname), buf);
  console.log(`  ${fname}  ${(buf.length / 1024).toFixed(1)}KB`);
  const face = b.face.replace(urlMatch[1], `/fonts/${fname}`);
  out.push(`/* ${fam} ${weight} — ${b.subset} */\n${face}`);
}

await writeFile(
  path.resolve("src/fonts.css"),
  `/* Self-hosted fonts (generated by scripts/selfhost_fonts.mjs — do not edit
   * by hand; re-run the script to refresh). Replaces fonts.googleapis.com —
   * same-origin preloaded fonts apply before first paint, eliminating the
   * font-swap reflow (CLS) and the third-party render-blocking CSS. */\n\n${out.join("\n\n")}\n`,
);
console.log("wrote src/fonts.css");
